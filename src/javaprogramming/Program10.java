package javaprogramming;

public class Program10 {
    static void main(String[] args) {
        //Find the sum of numbers from 1 to 100.
        System.out.println("Find the sum of numbers from 1 to 100.");
        int sum=0;
        for(int i=0;i<=100;i++)
        {
            sum=sum+i;
        }
        System.out.println(sum);
    }
}
